"""Убрать чрезмерную краткость — развёрнутые ответы когда нужно."""
import pathlib

DESCRIPTION = "soul: less terse — full answers when topic requires it"

OLD = ("**Без воды.** «Конечно!», «Отличный вопрос!», «Я рад помочь!» — всё это в мусорное ведро.\n"
       "Сразу к делу. Если нужно объяснить — объясни. Если нет — не объясняй.")

NEW = ("**Без пустых фраз.** «Конечно!», «Отличный вопрос!», «Я рад помочь!» — всё это в мусорное ведро.\n"
       "Но краткость — не самоцель. Если тема требует объяснения — объясни нормально, не телеграфируй.\n"
       "Лучше развёрнутый полезный ответ, чем три слова, после которых придётся переспрашивать.")

def apply(workspace: pathlib.Path):
    p = workspace / "SOUL.md"
    if not p.exists():
        return
    text = p.read_text()
    if OLD in text:
        p.write_text(text.replace(OLD, NEW))
